/**
 * @file TurtleShipTypes.h
 * @brief Common data types, pixel format enumerations, and bitmap structures for the TurtleShip GUI library.
 * @author Yoon-Ki Hong
 */

#ifndef YSS_GUI_UTIL__H_
#define YSS_GUI_UTIL__H_

#include <stdint.h>

/**
 * @struct position_t
 * @brief Legacy 2D signed coordinate structure.
 */
typedef struct
{
	int16_t x; ///< X-axis coordinate in pixels.
	int16_t y; ///< Y-axis coordinate in pixels.
}position_t;

/**
 * @struct Position_t
 * @brief 2D signed coordinate structure representing an (x, y) point on a canvas.
 */
typedef struct
{
	int16_t x; ///< X-axis coordinate in pixels.
	int16_t y; ///< Y-axis coordinate in pixels.
}Position_t;

/**
 * @struct Size_t
 * @brief 2D unsigned dimension structure representing width and height in pixels.
 */
typedef struct
{
	uint16_t width;  ///< Horizontal dimension in pixels.
	uint16_t height; ///< Vertical dimension in pixels.
}Size_t;

/**
 * @struct Bitmap_t
 * @brief Legacy bitmap descriptor holding dimensions, raw pixel format code, and pixel buffer pointer.
 */
typedef struct
{
	uint16_t width;  ///< Bitmap width in pixels.
	uint16_t height; ///< Bitmap height in pixels.
	uint8_t type;    ///< Pixel format type (0: RGB565, 1: RGB888, 2: ARGB1555).
	uint8_t *data;   ///< Pointer to raw pixel data buffer.
}Bitmap_t;

/**
 * @enum bitmapType_t
 * @brief Supported pixel color formats for bitmap images in TurtleShip.
 */
typedef enum
{
	BITMAP_TYPE_RGB565 = 0, ///< 16-bit RGB565 format (5-bit Red, 6-bit Green, 5-bit Blue).
	BITMAP_TYPE_RGB888,     ///< 24-bit RGB888 format (8-bit Red, 8-bit Green, 8-bit Blue).
	BITMAP_TYPE_ARGB1555    ///< 16-bit ARGB1555 format (1-bit Alpha, 5-bit Red, 5-bit Green, 5-bit Blue).
}bitmapType_t;

/**
 * @struct bitmap_t
 * @brief Standard bitmap descriptor used by Brush, FrameBuffer, and TftLcdDriver drawing APIs.
 *
 * @details
 * Holds the dimensions (`width`, `height`), pixel encoding (`type`), and a pointer (`data`)
 * to the contiguous pixel array. Bitmap assets generated by `yssBmpMaker` or exported from
 * a `FrameBuffer` via `FrameBuffer::getBitmap()` use this structure.
 *
 * ### Example Usage in User Application
 * @code
 * #include <TurtleShipTypes.h>
 *
 * extern const bitmap_t NuvotonLogo;
 *
 * void drawLogo(void)
 * {
 *     lcd.lock();
 *     lcd.drawBitmap({20, 30}, NuvotonLogo);
 *     lcd.unlock();
 * }
 * @endcode
 */
typedef struct 
{
	uint16_t width;    ///< Bitmap width in pixels.
	uint16_t height;   ///< Bitmap height in pixels.
	bitmapType_t type; ///< Pixel format type (0: RGB565, 1: RGB888, 2: ARGB1555).
	uint8_t *data;     ///< Pointer to the raw pixel array.
}bitmap_t;

/**
 * @struct BitmapFile_t
 * @brief Packed header layout for serialized binary bitmap files.
 */
typedef struct __attribute__((packed))
{
	uint16_t width;      ///< Bitmap width in pixels.
	uint16_t height;     ///< Bitmap height in pixels.
	uint8_t type;        ///< Pixel format type (0: RGB565, 1: RGB888, 2: ARGB1555).
	uint8_t reserved[3]; ///< Reserved padding bytes for alignment.
	uint8_t data;        ///< First byte of the variable-length pixel data payload.
}BitmapFile_t;

extern "C"
{
	/**
	 * @brief Fills a memory buffer with a repeated 24-bit RGB888 pixel pattern.
	 * @param[out] des     Destination buffer pointer where the RGB888 pixel pattern will be written.
	 * @param[in]  pattern 24-bit RGB888 color pattern to repeat.
	 * @param[in]  count   Number of pixels to write into the destination buffer.
	 * @author Yoon-Ki Hong
	 */
	void copyRgb888DotPattern(void *des, uint32_t pattern, uint32_t count);
}

#endif
