/**
 * @file CodeFont.h
 * @brief ROM/Flash-resident bitmap font class (`CodeFont`) of the TurtleShip GUI library.
 * @author Yoon-Ki Hong
 */

#ifndef YSS_GUI_CODE_FONT__H_
#define YSS_GUI_CODE_FONT__H_

/**
 * @brief Number of hash groups used in `CodeFont` glyph lookup tables.
 */
#define NUM_OF_GROUP 8

#include <stdint.h>
#include "Font.h"

/**
 * @class CodeFont
 * @brief Concrete `Font` implementation backed by C-array glyph tables stored in program memory (Flash/ROM).
 *
 * @details
 * `CodeFont` wraps a `codeFontInfo_t` table generated by the yss OS font generator tool
 * (e.g. `Font_Ubuntu_14_B`, `Font_Ubuntu_20_B`). To accelerate glyph lookup without requiring
 * a large flat array across the entire Unicode range, characters are partitioned into
 * `NUM_OF_CHAR_GROUP` (8) buckets indexed by the lowest 3 bits of the UTF-8 code (`ch & 0x07`).
 *
 * ### Example Usage in User Application
 * @code
 * #include <bsp.h>
 * #include <font/Ubuntu_14_B.h>
 * #include <font/Ubuntu_20_B.h>
 *
 * // In Ubuntu_14_B.h:
 * // extern CodeFont Font_Ubuntu_14_B;
 *
 * void showCalibrationScreen(void)
 * {
 *     lcd.lock();
 *     brush.setSize(210, 23);
 *     brush.setFont(Font_Ubuntu_20_B);
 *     brush.setBackgroundColor({0x00, 0x00, 0x00});
 *     brush.setBrushColor({0xFF, 0xFF, 0x30});
 *     brush.clear();
 *     brush.drawString(Brush::ALIGN_CENTER_MID, "[Touch Calibration]");
 *     lcd.drawBitmap({15, 100}, brush.getBitmap());
 *     lcd.unlock();
 * }
 * @endcode
 */
class CodeFont : public Font
{
public :
	/**
	 * @struct codeFontInfo_t
	 * @brief Packed master header for a Flash-resident `CodeFont` asset.
	 */
	struct codeFontInfo_t
	{
		uint8_t size;                                            ///< Nominal font height in pixels.
		uint32_t numOfChar[NUM_OF_CHAR_GROUP];                   ///< Number of glyphs stored in each of the 8 hash groups.
		const Font::fontInfo_t *fontInfo[NUM_OF_CHAR_GROUP];     ///< Pointers to the glyph descriptor arrays for each group.
	} __attribute__((packed));
	
	/**
	 * @brief Constructs a `CodeFont` instance bound to a static `codeFontInfo_t` descriptor table.
	 * @param[in] info Pointer to the static `codeFontInfo_t` structure in Flash/ROM.
	 * @author Yoon-Ki Hong
	 * @post Initializes `mSize` to `info->size` and `mSpaceWidth` to `mSize / 3`.
	 */
	CodeFont(const codeFontInfo_t *info);

	/**
	 * @brief Searches the appropriate hash group in `mInfo` for the glyph matching `ch`.
	 * @param[in] ch Packed UTF-8 character code.
	 * @return Pointer to the matching `Font::fontInfo_t` entry, or `nullptr` (`0`) if not found.
	 * @author Yoon-Ki Hong
	 */
	virtual fontInfo_t* getFontInfo(uint32_t ch) override;

private :
	const codeFontInfo_t *mInfo; ///< Pointer to the static font table in Flash/ROM.
};

#endif
