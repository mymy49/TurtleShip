/**
 * @file Font.h
 * @brief Abstract base class for bitmap font decoding, glyph lookup, and string metric calculation.
 * @author Yoon-Ki Hong
 * @date 2015
 */

#ifndef YSS_GUI_FONT__H_
#define YSS_GUI_FONT__H_

/**
 * @brief Number of printable ASCII character slots.
 */
#define NUM_OF_ASCII_CODE 96

/**
 * @brief Maximum number of font sub-headers.
 */
#define YSS_FONT_MAX_SUB_HEADER 8

/**
 * @brief Number of hash groups used to partition character glyph tables.
 */
#define NUM_OF_CHAR_GROUP 8

#include <stdint.h>

/**
 * @class Font
 * @brief Abstract base class providing UTF-8 character decoding, glyph metric lookup, and text width/height calculation.
 *
 * @details
 * `Font` defines the interface between `Brush` text rendering methods (`Brush::drawChar()`,
 * `Brush::drawString()`, `Brush::calculateStringArea()`) and concrete font storage backends
 * such as `CodeFont` (ROM/Flash C-array fonts generated by the yss font tool).
 *
 * Each glyph is described by a packed `fontInfo_t` structure containing its 32-bit packed UTF-8 code,
 * pixel dimensions (`width`, `height`), bearing offsets (`xpos`, `ypos`), and a pointer to the
 * 4-bit-per-pixel anti-aliased alpha bitmap (`data`).
 *
 * Users can optionally override the advance width of space characters (`setSpaceWidth()`),
 * period/dot characters (`setDotWidth()`), or enforce a minimum monospace-like character advance
 * width (`setCharWidth()`).
 *
 * ### Example Usage in User Application
 * @code
 * #include <bsp.h>
 * #include <font/Ubuntu_14_B.h>
 * #include <font/Ubuntu_20_B.h>
 *
 * void renderTitleText(void)
 * {
 *     brush.setSize(240, 20);
 *     brush.setBackgroundColor({0xFF, 0xFF, 0xFF});
 *     brush.setBrushColor({0x00, 0x00, 0x00});
 *     brush.setFont(Font_Ubuntu_14_B);
 *
 *     brush.clear();
 *     brush.drawString(Brush::ALIGN_CENTER_MID, "NuMaker-M251KG V1.1");
 *     lcd.drawBitmap({0, 100}, brush.getBitmap());
 * }
 * @endcode
 */
class Font
{
public:
	/**
	 * @struct fontInfo_t
	 * @brief Packed glyph descriptor holding UTF-8 code, bounding metrics, and 4-bit alpha bitmap pointer.
	 */
	struct fontInfo_t
	{
		uint32_t utf8Code; ///< Packed 1- to 3-byte UTF-8 character code.
		uint8_t width;     ///< Glyph bitmap width in pixels.
		uint8_t height;    ///< Glyph bitmap height in pixels.
		uint8_t xpos;      ///< Horizontal bearing offset in pixels (interpreted as signed `int8_t`).
		uint8_t ypos;      ///< Vertical bearing offset from the top of the character cell (interpreted as signed `int8_t`).
		uint8_t *data;     ///< Pointer to packed 4-bit grayscale/alpha glyph bitmap data (2 pixels per byte).
	} __attribute__((packed));

	/**
	 * @brief Constructs a `Font` object with default metric overrides initialized to zero.
	 * @param[in] none
	 * @return none
	 * @author Yoon-Ki Hong
	 * @date 2015
	 * @warning None.
	 * @note None.
	 * @pre None.
	 * @post None.
	 * @deprecated None.
	 */
	Font(void);

	/**
	 * @brief Looks up the glyph descriptor (`fontInfo_t`) for the given packed UTF-8 character code.
	 * @param[in] ch Packed UTF-8 character code returned by `getUtf8()`.
	 * @return Pointer to the matching `fontInfo_t` descriptor, or `nullptr` (`0`) if the glyph is not present.
	 * @author Yoon-Ki Hong
	 * @date 2015
	 * @warning None.
	 * @note None.
	 * @pre None.
	 * @post None.
	 * @deprecated None.
	 */
	virtual fontInfo_t* getFontInfo(uint32_t ch) = 0;

	/**
	 * @brief Gets the configured horizontal advance width for the ASCII space character (`' '`).
	 * @param[in] none
	 * @return Space advance width in pixels (`0` if using the default space width).
	 * @author Yoon-Ki Hong
	 * @date 2015
	 * @warning None.
	 * @note None.
	 * @pre None.
	 * @post None.
	 * @deprecated None.
	 */
	uint8_t getSpaceWidth(void);

	/**
	 * @brief Sets a custom horizontal advance width for the ASCII space character (`' '`).
	 * @param[in] width Space width in pixels (`0` to revert to the default space width).
	 * @return none
	 * @author Yoon-Ki Hong
	 * @date 2015
	 * @warning None.
	 * @note None.
	 * @pre None.
	 * @post None.
	 * @deprecated None.
	 */
	void setSpaceWidth(uint8_t width);

	/**
	 * @brief Gets the configured minimum horizontal advance width for regular characters.
	 * @param[in] none
	 * @return Minimum character advance width in pixels (`0` if proportional glyph widths are used).
	 * @author Yoon-Ki Hong
	 * @date 2015
	 * @warning None.
	 * @note None.
	 * @pre None.
	 * @post None.
	 * @deprecated None.
	 */
	uint8_t getCharWidth(void);

	/**
	 * @brief Sets a fixed minimum horizontal advance width for regular characters (useful for tabular numbers).
	 * @param[in] width Minimum character advance width in pixels (`0` for proportional spacing).
	 * @return none
	 * @author Yoon-Ki Hong
	 * @date 2015
	 * @warning None.
	 * @note None.
	 * @pre None.
	 * @post None.
	 * @deprecated None.
	 */
	void setCharWidth(uint8_t width);

	/**
	 * @brief Gets the configured horizontal advance width for the period/dot character (`'.'`).
	 * @param[in] none
	 * @return Dot advance width in pixels (`0` if using the glyph's natural width).
	 * @author Yoon-Ki Hong
	 * @date 2015
	 * @warning None.
	 * @note None.
	 * @pre None.
	 * @post None.
	 * @deprecated None.
	 */
	uint8_t getDotWidth(void);

	/**
	 * @brief Sets a custom horizontal advance width for the period/dot character (`'.'`).
	 * @param[in] width Dot advance width in pixels (`0` to use the glyph's natural width).
	 * @return none
	 * @author Yoon-Ki Hong
	 * @date 2015
	 * @warning None.
	 * @note None.
	 * @pre None.
	 * @post None.
	 * @deprecated None.
	 */
	void setDotWidth(uint8_t width);

	/**
	 * @brief Calculates the total horizontal width in pixels of a null-terminated UTF-8 string.
	 * @param[in] str Null-terminated UTF-8 string to measure.
	 * @return Total string width in pixels.
	 * @author Yoon-Ki Hong
	 * @date 2015
	 * @warning None.
	 * @note None.
	 * @pre None.
	 * @post None.
	 * @deprecated None.
	 */
	uint16_t getStringWidth(const char *str);

	/**
	 * @brief Gets the nominal line height (font size) in pixels.
	 * @param[in] none
	 * @return Nominal font height in pixels (`mSize`).
	 * @author Yoon-Ki Hong
	 * @date 2015
	 * @warning None.
	 * @note None.
	 * @pre None.
	 * @post None.
	 * @deprecated None.
	 */
	uint16_t getStringHeight(void);

	/**
	 * @brief Decodes the next UTF-8 character from `*src` and advances the `*src` pointer past the decoded bytes.
	 * @param[in,out] src Pointer to a C-string pointer; advanced by 1, 2, or 3 bytes depending on the UTF-8 sequence length.
	 * @return Packed 32-bit UTF-8 code (1-byte ASCII in `[7:0]`, 2-byte sequence in `[15:0]`, 3-byte sequence in `[23:0]`),
	 *         or `0` if an invalid byte (`0x80` ~ `0xBF`) is encountered.
	 * @author Yoon-Ki Hong
	 * @date 2015
	 * @warning None.
	 * @note None.
	 * @pre None.
	 * @post None.
	 * @deprecated None.
	 */
	uint32_t getUtf8(const char **src);

protected:
	uint8_t mSpaceWidth; ///< Custom horizontal advance width for `' '` (`0` = default).
	uint8_t mCharWidth;  ///< Custom minimum horizontal advance width for characters (`0` = proportional).
	uint8_t mSize;       ///< Nominal font height in pixels.
	uint8_t mDotWidth;   ///< Custom horizontal advance width for `'.'` (`0` = proportional).
};

#endif
